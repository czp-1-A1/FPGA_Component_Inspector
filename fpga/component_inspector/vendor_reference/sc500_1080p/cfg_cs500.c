void cs500_init(XIicPs *I2C_Ptr)
{
    int i = 0;
    I2C_ADDR16 I2C_WINST_16;

    while (reg_cs500[i].reg_addr != CFG_END) {

    	I2C_WINST_16.reg_addr[0] = reg_cs500[i].reg_addr>>8;
    	I2C_WINST_16.reg_addr[1] = reg_cs500[i].reg_addr;
    	I2C_WINST_16.reg_buf [0] = reg_cs500[i].reg_val;
    	i2cps_wr16(I2C_Ptr,&I2C_WINST_16,1,0x36);
		i++;
	}

}


